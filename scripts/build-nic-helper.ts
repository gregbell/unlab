// Builds src/runtime/unlab-nic.c for the guest and embeds the binary in
// src/runtime/nic-helper.ts. Needs zig on the PATH, for its cross compiler:
//   npm run nic-helper
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const SOURCE = new URL("../src/runtime/unlab-nic.c", import.meta.url);
const MODULE = new URL("../src/runtime/nic-helper.ts", import.meta.url);

const dir = mkdtempSync(join(tmpdir(), "unlab-nic-"));
try {
	const out = join(dir, "unlab-nic");
	execFileSync(
		"zig",
		["cc", "-target", "aarch64-linux-musl", "-static", "-Oz", "-s", "-Wall", "-Wextra", "-Werror"].concat(
			"-o",
			out,
			SOURCE.pathname,
		),
		{ stdio: "inherit" },
	);
	const binary = readFileSync(out);
	const sha256 = createHash("sha256").update(readFileSync(SOURCE)).digest("hex");
	writeFileSync(
		MODULE,
		[
			"// Generated by scripts/build-nic-helper.ts from unlab-nic.c. Do not edit.",
			"",
			"/** The SHA-256 of the source this was built from. */",
			`export const SOURCE_SHA256 = "${sha256}";`,
			"",
			"/** A static aarch64 Linux executable. */",
			`export const NIC_HELPER = Uint8Array.from(atob("${binary.toString("base64")}"), (c) => c.charCodeAt(0));`,
			"",
		].join("\n"),
	);
	console.log(`unlab-nic is ${binary.length} bytes`);
} finally {
	rmSync(dir, { recursive: true });
}
